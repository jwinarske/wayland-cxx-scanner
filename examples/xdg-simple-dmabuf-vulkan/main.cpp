static void PrintUsage(const char* argv0) {
  std::printf(
      "Usage: %s [OPTIONS]\n"
      "\n"
      "Render a DMA-BUF-backed Vulkan triangle on a Wayland compositor.\n"
      "\n"
      "Options:\n"
      "  -f, --drm-format FORMAT  DRM pixel format name (default: XRGB8888)\n"
      "  -w, --width N            Window width  in pixels (default: 250)\n"
      "  -h, --height N           Window height in pixels (default: 250)\n"
      "      --help               Print this help and exit\n"
      "\n"
      "Supported DRM formats: XRGB8888, ARGB8888\n",
      argv0);
}

// Helper: parse a positive integer from a C string (used by getopt cases).
static bool ParsePositiveInt(const char* prog,
                             const char* flag,
                             const char* val_str,
                             int& out) {
  char* end = nullptr;
  errno = 0;
  const long val = std::strtol(val_str, &end, 10);
  if (errno == ERANGE || end == val_str || *end != '\0' || val <= 0 ||
      val > INT_MAX) {
    std::fprintf(stderr, "%s: invalid %s '%s'\n", prog, flag, val_str);
    return false;
  }
  out = static_cast<int>(val);
  return true;
}

int main(int argc, char** argv) {
  // Suppress SIGPIPE so a compositor disconnect during wl_display_flush is
  // reported as EPIPE / error return rather than terminating the process.
  std::signal(SIGPIPE, SIG_IGN);

  // getopt_long requires raw argc/argv, but capture argv[0] once to avoid
  // repeated pointer arithmetic elsewhere.
  const char* const prog =
      argv[0];  // NOLINT(cppcoreguidelines-pro-bounds-pointer-arithmetic)

  App::Options opts{};

  // NOLINTBEGIN(cppcoreguidelines-avoid-c-arrays)
  static constexpr option kLongOpts[] = {
      {"drm-format", required_argument, nullptr, 'f'},
      {"width", required_argument, nullptr, 'w'},
      {"height", required_argument, nullptr, 'h'},
      {"help", no_argument, nullptr, '?'},
      {nullptr, 0, nullptr, 0},
  };
  // NOLINTEND(cppcoreguidelines-avoid-c-arrays)

  int opt;
  while ((opt = getopt_long(argc, argv, "f:w:h:", kLongOpts, nullptr)) != -1) {
    switch (opt) {
      case 'f': {
        const uint32_t code = ParseDrmFormat(optarg);
        if (!code) {
          std::fprintf(stderr,
                       "%s: unknown DRM format '%s'; "
                       "supported: XRGB8888, ARGB8888\n",
                       prog, optarg);
          return EXIT_FAILURE;
        }
        opts.drm_format = code;
        break;
      }
      case 'w':
        if (!ParsePositiveInt(prog, "width", optarg, opts.width))
          return EXIT_FAILURE;
        break;
      case 'h':
        if (!ParsePositiveInt(prog, "height", optarg, opts.height))
          return EXIT_FAILURE;
        break;
      case '?':
        PrintUsage(prog);
        return EXIT_SUCCESS;
      default:
        PrintUsage(prog);
        return EXIT_FAILURE;
    }
  }

  App app{opts};
  return app.Run();
}
