// ── WlBufferHandler ──────────────────────────────────────────────────────────
// Tracks wl_buffer.release so we know when the compositor is done reading the
// DMA-BUF.  released_ starts true, so the very first RenderFrame() proceeds.
// When release fires, it notifies App so that a frame callback that arrived
// before the buffer was released can be served immediately (REC-1).

class WlBufferHandler : public wayland::client::CWlBuffer<WlBufferHandler> {
 public:
  App* app_ = nullptr;
  bool released_ = true;
  void OnRelease() override;  // defined after full App definition
};

// ── LinuxDmabufHandler ───────────────────────────────────────────────────────
// Receives format/modifier advertisements from zwp_linux_dmabuf_v1 and checks
// that the compositor supports the requested DRM pixel format.

class LinuxDmabufHandler
    : public linux_dmabuf_unstable_v1::client::CZwpLinuxDmabufV1<
          LinuxDmabufHandler> {
 public:
  uint32_t desired_format = DRM_FORMAT_XRGB8888;
  bool has_format = false;

  void OnFormat(const uint32_t format) override {
    if (format == desired_format)
      has_format = true;
  }
  void OnModifier(const uint32_t format,
                  uint32_t /*mod_hi*/,
                  uint32_t /*mod_lo*/) override {
    if (format == desired_format)
      has_format = true;
  }
};

